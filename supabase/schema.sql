-- Northstar Check is a fictional scam-awareness survey.
create table if not exists public.demo_submissions (
  id bigint generated by default as identity primary key,
  name text check (name is null or char_length(trim(name)) between 1 and 100),
  scenario_response text not null check (scenario_response in (
    'Open the link to check',
    'Check the official app or website',
    'Reply to ask for details',
    'Delete it immediately'
  )),
  warning_sign text not null check (warning_sign in (
    'Unexpected request',
    'Pressure to act now',
    'Unusual link or sender',
    'More than one of these'
  )),
  location text check (location is null or char_length(trim(location)) between 1 and 100),
  created_at timestamptz default now()
);

alter table public.demo_submissions enable row level security;

revoke all on public.demo_submissions from anon, authenticated;
grant insert (name, scenario_response, warning_sign, location) on public.demo_submissions to anon, authenticated;
grant select on public.demo_submissions to authenticated;

drop policy if exists "Audience can submit survey responses" on public.demo_submissions;
create policy "Audience can submit survey responses"
  on public.demo_submissions for insert
  to anon, authenticated
  with check (
    scenario_response in (
      'Open the link to check',
      'Check the official app or website',
      'Reply to ask for details',
      'Delete it immediately'
    )
    and warning_sign in (
      'Unexpected request',
      'Pressure to act now',
      'Unusual link or sender',
      'More than one of these'
    )
  );

drop policy if exists "Authenticated presenters can view entries" on public.demo_submissions;
create policy "Authenticated presenters can view entries"
  on public.demo_submissions for select
  to authenticated
  using (true);

do $$
begin
  alter publication supabase_realtime add table public.demo_submissions;
exception when duplicate_object then null;
end $$;